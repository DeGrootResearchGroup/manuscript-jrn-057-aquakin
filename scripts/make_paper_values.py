def _load(name):
    with open(os.path.join(common.RESULTS_DIR, name + ".json")) as f:
        return json.load(f)


def sci(x, nd=1):
    """Format as ``m\\times10^{e}`` for LaTeX math mode."""
    x = float(x)
    if x == 0:
        return "0"
    import math
    e = int(math.floor(math.log10(abs(x))))
    m = x / 10 ** e
    return f"{m:.{nd}f}\\times10^{{{e}}}"


def pct(x, nd=1):
    return f"{float(x):.{nd}f}"


def smallpct(x):
    """A percentage that may be round-off small: plain for >=0.1, else sci math."""
    x = float(x)
    return f"{x:.1f}" if x >= 0.1 else f"${sci(x)}$"


_NUMBER_WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven",
                 "eight", "nine"]


def words(x):
    """Spell out an integer count below 10 (house style); numerals from 10 up."""
    n = int(x)
    return _NUMBER_WORDS[n] if 0 <= n < 10 else str(n)


def _sym(name):
    """ASM state/param name -> LaTeX math symbol, e.g. SNO -> $S_{NO}$,
    XB_H -> $X_{B,H}$, muH -> $\\mu_H$, Y_H -> $Y_H$, KNH_A -> $K_{NH,A}$."""
    greek = {"muH": r"\mu_H", "muA": r"\mu_A", "etag": r"\eta_g", "etah": r"\eta_h"}
    if name in greek:
        return f"${greek[name]}$"
    var = name[0]
    rest = name[1:].lstrip("_").replace("_", ",")
    if not rest:
        return f"${var}$"
    return f"${var}_{{{rest}}}$"


