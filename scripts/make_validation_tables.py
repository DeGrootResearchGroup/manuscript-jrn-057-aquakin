"""Generate paper/validation_tables.tex: the full per-species BSM1 validation.

A longtable of the open-loop steady-state reactor comparison (reference, aquakin,
relative %), and a short table of the dry-weather dynamic effluent averages. Reads
the same result caches as the figures.
"""
from __future__ import annotations
import json
import os

import common

OUT = os.path.join(common.ROOT, "paper", "validation_tables.tex")


def _load(name):
    with open(os.path.join(common.RESULTS_DIR, name + ".json")) as f:
        return json.load(f)


def _sym(name):
    greek = {"muH": r"\mu_H", "muA": r"\mu_A"}
    if name in greek:
        return f"${greek[name]}$"
    var, rest = name[0], name[1:].lstrip("_").replace("_", ",")
    return f"${var}_{{{rest}}}$" if rest else f"${var}$"


def main():
    s = _load("bsm1_steady")
    dy = _load("bsm1_dynamic")
    L = []

    # --- steady-state reactor longtable ---
    L.append("% Auto-generated by scripts/make_validation_tables.py.")
    L.append(r"\begin{longtable}{llrrr}")
    L.append(r"\caption{Open-loop BSM1 steady-state validation: the aquakin "
             r"activated-sludge reactor composition against the published "
             r"benchmark reference, per reactor and species.}"
             r"\label{tab:steady}\\")
    L.append(r"\toprule")
    L.append(r"Reactor & Species & Reference & aquakin & Rel.\ \% \\")
    L.append(r"\midrule\endfirsthead")
    L.append(r"\toprule Reactor & Species & Reference & aquakin & Rel.\ \% \\"
             r"\midrule\endhead")
    L.append(r"\bottomrule\endfoot")
    for lab, m, r in zip(s["rlabels"], s["rmodel"], s["rref"]):
        tk, sp = lab.split(".", 1)
        tkn = f"Tank {tk[len('tank'):]}"
        rel = abs(m - r) / abs(r) * 100
        L.append(f"{tkn} & {_sym(sp)} & {r:.4g} & {m:.4g} & {rel:.2g} \\\\")
    L.append(r"\end{longtable}")
    L.append("")

    # --- dynamic effluent table ---
    L.append(r"\begin{table}[H]\centering")
    L.append(r"\caption{Open-loop BSM1 dry-weather dynamic validation: the "
             r"aquakin effluent averaged over days 7--14 against the reference.}"
             r"\label{tab:dynamic}")
    L.append(r"\begin{tabular}{lrrr}")
    L.append(r"\toprule")
    L.append(r"Quantity & Reference & aquakin & Rel.\ \% \\\midrule")
    units = {"SNH": "mg N/L", "total N": "mg N/L", "total COD": "mg COD/L",
             "TSS": "mg SS/L"}
    names = {"SNH": "$S_{NH}$", "total N": "Total N", "total COD": "Total COD", "TSS": "TSS"}
    for k, (m, r) in dy["comp"].items():
        rel = abs(m - r) / abs(r) * 100
        L.append(f"{names.get(k, k)} ({units.get(k,'')}) & {r:.3f} & {m:.3f} & {rel:.2g} \\\\")
    L.append(r"\midrule")
    L.append(f"EQI ({dy['eqi_conv']}) & {dy['eqi_ref']:.0f} & {dy['eqi']:.0f} "
             f"& {dy['eqi_pct']:.2g} \\\\")
    L.append(f"OCI ({dy['oci_conv']}) & {dy['oci_ref']:.0f} & {dy['oci']:.0f} "
             f"& {dy['oci_pct']:.2g} \\\\")
    L.append(r"\bottomrule")
    L.append(r"\end{tabular}")
    L.append(r"\end{table}")
    L.append("")

    # --- standalone ADM1 digester longtable (sorted by descending rel. error) ---
    dg = _load("digester_validation")
    order = sorted(range(len(dg["names"])), key=lambda i: -dg["rel_pct"][i])
    L.append(r"\begin{longtable}{lrrrr}")
    L.append(r"\caption{Standalone ADM1 digester verification: the aquakin "
             r"digester composition, run as a single unit on the published BSM2 "
             r"digester feed, against the published BSM2 open-loop digester steady "
             r"state, sorted by descending relative error. The two aquakin columns "
             r"are the steady-state result (the algebraic root of $\mathrm{d}y/"
             r"\mathrm{d}t=0$ by pseudo-transient continuation) and the dynamic "
             r"result (forward-integrated for 300\,d to the same attractor); the relative "
             r"error is the steady-state result versus the reference. Units are "
             r"kg\,COD\,m$^{-3}$ except $S_{IC}$/$S_{IN}$ (kmol\,m$^{-3}$) and the "
             r"headspace carbon dioxide $S_{gas,co2}$ (kmol\,C\,m$^{-3}$); the headspace "
             r"gases are concentrations, not partial pressures.}\label{tab:si-digester}\\")
    L.append(r"\toprule")
    L.append(r"State & Reference & Steady-state & Dynamic & Rel.\ \% \\")
    L.append(r"\midrule\endfirsthead")
    L.append(r"\toprule State & Reference & Steady-state & Dynamic & Rel.\ \% \\"
             r"\midrule\endhead")
    L.append(r"\bottomrule\endfoot")
    for i in order:
        nm = "\\texttt{" + dg["names"][i].replace("_", "\\_") + "}"
        L.append(f"{nm} & {dg['ref'][i]:.4g} & {dg['model'][i]:.4g} & "
                 f"{dg['forward'][i]:.4g} & {dg['rel_pct'][i]:.2g} \\\\")
    L.append(r"\end{longtable}")

    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"  wrote {os.path.relpath(OUT, common.ROOT)}")


if __name__ == "__main__":
    main()
